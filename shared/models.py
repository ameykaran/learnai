"""
Shared data models for the learning management system.
These models are used across agents and stored in the orchestrator's memory.
"""

from dataclasses import dataclass, field, asdict
from typing import List, Dict, Optional
from datetime import datetime
import json


@dataclass
class UserProfile:
    """
    User profile generated by onboarding assessment.
    This is stored in the orchestrator's memory and used by other agents.
    """
    
    # User Identification
    user_id: str
    session_id: str
    
    # Assessment Results
    competence_level: str  # "easy" | "medium" | "difficult"
    ability_score: float  # 0.0 - 1.0 (IRT-based ability estimate)
    final_score: float  # Percentage correct (0-100)
    
    # Performance Breakdown by Difficulty
    easy_correct: int = 0
    easy_total: int = 0
    medium_correct: int = 0
    medium_total: int = 0
    difficult_correct: int = 0
    difficult_total: int = 0
    
    # Performance Metrics
    easy_accuracy: float = 0.0
    medium_accuracy: float = 0.0
    difficult_accuracy: float = 0.0
    overall_accuracy: float = 0.0
    
    # Topic Analysis (if available)
    strengths: List[str] = field(default_factory=list)
    weaknesses: List[str] = field(default_factory=list)
    
    # Recommendations for Main Workflow
    recommended_starting_level: str = "medium"  # Where to start in main curriculum
    suggested_topics: List[str] = field(default_factory=list)
    learning_pace: str = "normal"  # "slow" | "normal" | "fast"
    
    # Quiz Details
    total_questions: int = 25
    questions_answered: int = 0
    quiz_history: List[Dict] = field(default_factory=list)  # Full question-answer history
    
    # Metadata
    onboarding_completed: bool = False
    onboarding_started_at: Optional[datetime] = None
    onboarding_completed_at: Optional[datetime] = None
    
    def to_dict(self) -> dict:
        """Convert to dictionary for storage/transmission to orchestrator."""
        data = asdict(self)
        # Convert datetime objects to ISO format strings
        if self.onboarding_started_at:
            data['onboarding_started_at'] = self.onboarding_started_at.isoformat()
        if self.onboarding_completed_at:
            data['onboarding_completed_at'] = self.onboarding_completed_at.isoformat()
        return data
    
    def to_json(self) -> str:
        """Convert to JSON string."""
        return json.dumps(self.to_dict(), indent=2)
    
    @classmethod
    def from_dict(cls, data: dict) -> "UserProfile":
        """Create UserProfile from dictionary."""
        # Convert ISO format strings back to datetime
        if isinstance(data.get('onboarding_started_at'), str):
            data['onboarding_started_at'] = datetime.fromisoformat(data['onboarding_started_at'])
        if isinstance(data.get('onboarding_completed_at'), str):
            data['onboarding_completed_at'] = datetime.fromisoformat(data['onboarding_completed_at'])
        return cls(**data)
    
    @classmethod
    def from_quiz_results(cls, quiz_results: dict, user_id: str, session_id: str) -> "UserProfile":
        """
        Create UserProfile from quiz results.
        This is called when the onboarding assessment is complete.
        
        Args:
            quiz_results: Results dictionary from the adaptive quiz
            user_id: Unique user identifier
            session_id: Quiz session identifier
        
        Returns:
            UserProfile object ready for orchestrator memory
        """
        # Extract performance metrics
        total_correct = quiz_results.get('total_correct', 0)
        total_questions = quiz_results.get('total_questions', 25)
        overall_accuracy = quiz_results.get('overall_accuracy', 0) * 100  # Convert to percentage
        
        # Difficulty breakdown
        easy_stats = quiz_results.get('easy_stats', {})
        medium_stats = quiz_results.get('medium_stats', {})
        difficult_stats = quiz_results.get('difficult_stats', {})
        
        # Calculate accuracies
        easy_accuracy = easy_stats.get('accuracy', 0) * 100
        medium_accuracy = medium_stats.get('accuracy', 0) * 100
        difficult_accuracy = difficult_stats.get('accuracy', 0) * 100
        
        # Determine competence level
        competence_level = quiz_results.get('final_competence_level', 'medium')
        
        # Get ability score (from IRT model)
        ability_score = quiz_results.get('final_ability', 0.5)
        
        # Analyze strengths and weaknesses
        strengths = []
        weaknesses = []
        
        if easy_accuracy >= 80:
            strengths.append("basic_probability_concepts")
        if medium_accuracy >= 80:
            strengths.append("intermediate_probability")
        if difficult_accuracy >= 80:
            strengths.append("advanced_probability")
        
        if easy_accuracy < 60:
            weaknesses.append("basic_probability_concepts")
        if medium_accuracy < 60:
            weaknesses.append("intermediate_probability")
        if difficult_accuracy < 60:
            weaknesses.append("advanced_probability")
        
        # Determine learning pace based on performance
        if overall_accuracy >= 80 and medium_accuracy >= 70:
            learning_pace = "fast"
        elif overall_accuracy < 60:
            learning_pace = "slow"
        else:
            learning_pace = "normal"
        
        # Determine recommended starting level
        if competence_level == "easy":
            recommended_starting_level = "fundamentals"
        elif competence_level == "medium":
            recommended_starting_level = "intermediate"
        else:
            recommended_starting_level = "advanced"
        
        # Suggest topics based on weaknesses
        suggested_topics = []
        if "basic_probability_concepts" in weaknesses:
            suggested_topics.extend(["sample_spaces", "basic_events", "probability_rules"])
        if "intermediate_probability" in weaknesses:
            suggested_topics.extend(["conditional_probability", "independence", "combinations"])
        if "advanced_probability" in weaknesses:
            suggested_topics.extend(["bayes_theorem", "distributions", "expected_value"])
        
        return cls(
            user_id=user_id,
            session_id=session_id,
            competence_level=competence_level,
            ability_score=ability_score,
            final_score=overall_accuracy,
            easy_correct=easy_stats.get('correct', 0),
            easy_total=easy_stats.get('total', 0),
            medium_correct=medium_stats.get('correct', 0),
            medium_total=medium_stats.get('total', 0),
            difficult_correct=difficult_stats.get('correct', 0),
            difficult_total=difficult_stats.get('total', 0),
            easy_accuracy=easy_accuracy,
            medium_accuracy=medium_accuracy,
            difficult_accuracy=difficult_accuracy,
            overall_accuracy=overall_accuracy,
            strengths=strengths,
            weaknesses=weaknesses,
            recommended_starting_level=recommended_starting_level,
            suggested_topics=suggested_topics,
            learning_pace=learning_pace,
            total_questions=total_questions,
            questions_answered=total_correct,
            quiz_history=[],  # Can be populated if needed
            onboarding_completed=True,
            onboarding_completed_at=datetime.utcnow()
        )
    
    def get_summary(self) -> str:
        """Get a human-readable summary of the profile."""
        return f"""
User Profile Summary:
--------------------
User ID: {self.user_id}
Competence Level: {self.competence_level.upper()}
Overall Accuracy: {self.overall_accuracy:.1f}%
Ability Score: {self.ability_score:.3f}

Performance Breakdown:
- Easy: {self.easy_correct}/{self.easy_total} ({self.easy_accuracy:.1f}%)
- Medium: {self.medium_correct}/{self.medium_total} ({self.medium_accuracy:.1f}%)
- Difficult: {self.difficult_correct}/{self.difficult_total} ({self.difficult_accuracy:.1f}%)

Strengths: {', '.join(self.strengths) if self.strengths else 'None identified'}
Weaknesses: {', '.join(self.weaknesses) if self.weaknesses else 'None identified'}

Recommendations:
- Starting Level: {self.recommended_starting_level}
- Learning Pace: {self.learning_pace}
- Focus Topics: {', '.join(self.suggested_topics[:3]) if self.suggested_topics else 'Continue with standard curriculum'}
"""
